export function advLabel(fileOrPath, lang = "en") {
  const row = ADV_COPY[fileOrPath];
  if (!row) {
    const base = String(fileOrPath || "").split("/").pop();
    const nice = String(base || "")
      .replace(/_/g, " ")
      .replace(/\b\w/g, (c) => c.toUpperCase());
    return { title: nice, how: "—" };
  }
  return row[lang] || row.en;
}

