/** Build checklist table rows for a group of parsed advancements. */
export function advancementTableRows(list, lang = "en") {
  return (list || [])
    .map((a) => {
      const copyKey = ADV_COPY[a.path] ? a.path : a.file;
      const fromCopy = ADV_COPY[copyKey]?.[lang] || ADV_COPY[copyKey]?.en;
      const title = fromCopy?.title || a.titleEn || advLabel(copyKey, lang).title;
      const how = fromCopy?.how || a.descriptionEn || advLabel(copyKey, lang).how;
      const link = a.leaderSlug
        ? `<a href="${a.leaderSlug}.html">${escHtml(title)}</a>`
        : escHtml(title);
      return `<tr>
      <td>${link}</td>
      <td>${escHtml(how)}</td>
      <td>${escHtml(a.iconLabel || "—")}</td>
    </tr>`;
    })
    .join("");
}

function escHtml(s) {
  return String(s ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}
